import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import bundledChromium from '@sparticuz/chromium';
const browser=await chromium.launch({executablePath:await bundledChromium.executablePath(),args:bundledChromium.args,headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000');await page.waitForTimeout(4000);
await page.screenshot({path:'/home/user/studio-desktop.png'});
console.log('initial errors',errors);
await page.getByTitle('Add Basic Part to the scene',{exact:true}).click();
await page.waitForTimeout(200);
assert.equal(await page.locator('.selected-object b').textContent(),'Part');
await page.getByLabel('Position X',{exact:true}).fill('4');
assert.equal(await page.getByLabel('Position X',{exact:true}).inputValue(),'4');
await page.getByRole('button',{name:'Save project (Ctrl+S)',exact:true}).click();
await page.waitForTimeout(600);
await page.getByRole('button',{name:'Play',exact:true}).click();await page.waitForTimeout(600);await page.keyboard.press('w');
await page.getByRole('button',{name:'Stop preview',exact:true}).click();
await page.getByRole('button',{name:'Settings',exact:true}).click();
await page.screenshot({path:'/home/user/studio-settings.png'});
await page.keyboard.press('Escape');
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(600);await page.screenshot({path:'/home/user/studio-mobile.png'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.getByTitle('Compact Properties',{exact:true}).click();assert.equal(await page.locator('.properties').isVisible(),true);
await page.getByTitle('Compact Properties',{exact:true}).click();
await page.getByTitle('Compact Explorer',{exact:true}).click();assert.equal(await page.locator('.explorer').isVisible(),true);
console.log('PASS: add object, edit transform, save, play/stop, settings, responsive mobile drawers, no runtime errors.');
await browser.close();if(errors.length)process.exitCode=1;
